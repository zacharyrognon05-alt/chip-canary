"""Build the appendix tables of the research note from the result files (no number typed by hand).

Reads outputs/*.csv written by leadlag.py and event_study.py, writes paper/appendix_tables.md.

Usage:
    .venv/bin/python src/appendix_tables.py
"""

from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
DEST = ROOT / "paper" / "appendix_tables.md"


def fmt(x, nd=2):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return ""
    if isinstance(x, (float, np.floating)):
        return f"{x:.{nd}f}"
    return str(x)


def pval(p):
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return ""
    return "< 0.001" if p < 0.001 else f"{p:.3f}"


def table(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    # A "|" inside a cell would break the markdown table
    cell = lambda v: str(v).replace("|surprise|", "absolute surprise").replace("|", "/")
    return head + "\n".join("| " + " | ".join(cell(v) for v in row) + " |" for row in df.to_numpy())


def main() -> None:
    parts = ["# Appendix tables\n",
             "*Generated by `src/appendix_tables.py` from `outputs/`; do not edit by hand.*\n"]

    # A2. Part 1
    lead = pd.read_csv(OUT / "v1_1_lead_time_summary.csv")
    t = lead[["firm", "definition", "n_quarters", "median_days", "mean_days", "min_days", "max_days"]].copy()
    t["mean_days"] = t["mean_days"].map(fmt)
    t.columns = ["Firm", "Definition", "Quarters", "Median (days)", "Mean", "Min", "Max"]
    parts += ["## A2. Part 1, all specifications\n", "**V1-1. Lead time (descriptive)**\n", table(t), ""]

    corr = pd.read_csv(OUT / "v1_2_correlations.csv")
    holm = pd.read_csv(OUT / "v1_holm_family.csv")
    corr["test"] = "V1-2 " + corr["firm"] + ", " + corr["measure"]
    c = corr.merge(holm[["test", "p_holm"]], on="test")
    t = pd.DataFrame({
        "Firm": c["firm"], "Measure": c["measure"], "n": c["n"], "r": c["r"].map(fmt),
        "95% CI (Fisher)": c["fisher_lo"].map(fmt) + " to " + c["fisher_hi"].map(fmt),
        "95% CI (block bootstrap)": c["boot_lo"].map(fmt) + " to " + c["boot_hi"].map(fmt),
        "p (Holm)": c["p_holm"].map(pval), "Expected": c["expected"],
        "Verdict (Fisher / bootstrap)": c["verdict_fisher"] + " / " + c["verdict_boot"]})
    parts += ["**V1-2. Correlations, 2016Q3-2026Q2**\n", table(t), ""]

    comp = pd.read_csv(OUT / "v1_3_comparisons.csv")
    f3 = lambda v: fmt(v, 3)  # differences are small: three decimals
    t = pd.DataFrame({"Comparison": comp["comparison"], "n": comp["n"], "Difference in r": comp["difference"].map(f3),
                      "95% CI (bootstrap)": comp["boot_lo"].map(f3) + " to " + comp["boot_hi"].map(f3),
                      "p (raw)": comp["p_raw"].map(pval), "p (Holm)": comp["p_holm"].map(pval), "Verdict": comp["verdict"]})
    parts += ["**V1-3. Comparisons of correlations**\n", table(t), ""]

    e3 = pd.read_csv(OUT / "e3_pre2023_vs_full.csv")
    t = pd.DataFrame({"Firm": e3["firm"], "Measure": e3["measure"],
                      "Full sample r (n)": e3["r_full"].map(fmt) + " (" + e3["n_full"].astype(str) + ")",
                      "Before 2023 r (n)": e3["r_pre2023"].map(fmt) + " (" + e3["n_pre2023"].astype(str) + ")",
                      "Before 2023, 95% CI": e3["fisher_lo_pre2023"].map(fmt) + " to " + e3["fisher_hi_pre2023"].map(fmt)})
    parts += ["**E-3. Before vs during the AI boom (descriptive)**\n", table(t), ""]

    # A3. Part 2
    v2 = pd.read_csv(OUT / "v2_main.csv")
    t = pd.DataFrame({"Specification": v2["spec"], "n": v2["n"], "Estimate": v2["estimate"].map(fmt),
                      "95% CI": v2["ci_lo"].map(fmt) + " to " + v2["ci_hi"].map(fmt),
                      "p (raw)": v2["p_raw"].map(pval), "p (Holm, 22 tests)": v2["p_holm"].map(pval),
                      "Verdict": v2["verdict"]})
    parts += ["## A3. Part 2, all specifications (main sample 2016-2026)\n",
              "*V2-1: reaction ratio (1 = ordinary day). V2-2 to V2-4: gap in ordinary days. "
              "V2-5: slope of the signed reaction (ordinary days) on the predicted part.*\n", table(t), ""]

    # A4. Robustness
    r1 = pd.read_csv(OUT / "v1_robustness.csv")
    w = r1.pivot(index="spec", columns="variant", values="estimate").reset_index()
    w = w[["spec", "main", "r1 Comtrade for T1-T2", "r2 earnings in USD"]]
    for col in w.columns[1:]:
        w[col] = w[col].map(lambda v: fmt(v, 3))
    w.columns = ["Specification", "Main", "Comtrade for months 1-2", "Earnings in USD"]
    parts += ["## A4. Robustness\n", "**Part 1 (estimates)**\n", table(w), ""]

    r2 = pd.read_csv(OUT / "v2_robustness.csv")
    w = r2.pivot(index="spec", columns="variant", values="estimate")
    order = [c for c in ["main", "window [0,+3]", "market model, SOX", "without 2026-07-31",
                         "without unverified 2016-09", "overlaps included", "V2-5 on revenue",
                         "V2-5 exports from Comtrade", "V2-5 earnings in USD"] if c in w.columns]
    w = w[order].reindex(v2["spec"]).reset_index()
    for col in w.columns[1:]:
        w[col] = w[col].map(fmt)
    sig = r2.assign(sig=r2["p_holm"] < 0.05).pivot(index="spec", columns="variant", values="sig")[order].reindex(v2["spec"])
    for j, col in enumerate(order):
        w[col] = [f"{v}*" if (s is True and v) else v for v, s in zip(w[col], sig[col])]
    w.columns = ["Specification"] + order
    parts += ["**Part 2 (estimates; * = significant at 5% after Holm within the variant)**\n", table(w), "",
              "*Empty cell: not computable (fewer than 10 events, e.g. SK Hynix earnings with the [0,+3] "
              "window, almost all overlapping the first-20-days release). V2-5 with Comtrade exports: the SK "
              "Hynix slope falls to about -0.2 because Comtrade ends in 2025 and drops 2026Q2, the quarter that "
              "drives the main estimate (see section 5).*\n"]

    # A5. Exploratory
    ex = pd.read_csv(OUT / "exploratory_e1_e2.csv")
    t = pd.DataFrame({"Specification": ex["spec"], "n": ex["n"].astype(str), "Estimate": ex["estimate"].map(fmt),
                      "95% CI": ex["ci_lo"].map(fmt) + " to " + ex["ci_hi"].map(fmt),
                      "p (raw)": ex["p_raw"].map(pval), "Verdict": ex["verdict"], "Note": ex["note"].fillna("")})
    t.loc[t["Estimate"] == "", "95% CI"] = ""
    parts += ["## A5. Exploratory specifications (not in the Holm families)\n", table(t), ""]

    DEST.write_text("\n".join(parts) + "\n")
    print(f"Saved: {DEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
