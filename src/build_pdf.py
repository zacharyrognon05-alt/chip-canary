"""Build the PDF of the research note: dense layout (A4, 2 cm margins, 11 pt), appendix after the note.

paper/draft_full.md + paper/appendix.md + paper/appendix_tables.md -> HTML -> PDF with headless Chrome.
Run src/assemble_note.py and src/appendix_tables.py first if a section or a result changed.

Usage:
    .venv/bin/python src/build_pdf.py
"""

import re
import subprocess
from pathlib import Path

import markdown
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
HTML = PAPER / "chip_canary_note.html"
PDF = PAPER / "chip_canary_note.pdf"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"

CSS = """
@page { size: A4; margin: 2cm; }
body { font-family: "Times New Roman", Times, "Apple SD Gothic Neo", serif; font-size: 11pt;
       line-height: 1.32; color: #111; }
h1 { font-size: 17pt; margin: 0 0 2pt 0; }
h1 + p em { font-size: 11.5pt; }
h2 { font-size: 13pt; margin: 14pt 0 4pt 0; }
p { margin: 0 0 6pt 0; text-align: justify; hyphens: auto; }
ul { margin: 0 0 6pt 0; padding-left: 16pt; }
blockquote { margin: 8pt 0; padding: 6pt 10pt; border-left: 3px solid #888; background: #f3f3f1;
             font-size: 10pt; break-inside: avoid; }
blockquote p { margin: 0 0 3pt 0; }
table { border-collapse: collapse; width: 100%; font-size: 9pt; margin: 4pt 0 4pt 0; break-inside: avoid; }
th, td { border-bottom: 1px solid #bbb; padding: 2pt 4pt; text-align: left; vertical-align: top; }
th { border-bottom: 1.5px solid #333; }
img { display: block; width: 86%; margin: 4pt auto 0 auto; break-inside: avoid; }
.keep { break-inside: avoid; }
.keep-title { break-after: avoid; }
table.long { break-inside: auto; }
table.long tr { break-inside: avoid; }
h2 { break-after: avoid; }
.references p { text-align: left; font-size: 9.5pt; margin-bottom: 4pt; }
p:has(> img) { break-inside: avoid; margin-bottom: 0; }
.appendix { break-before: page; }
.appendix table { font-size: 7.5pt; }
.appendix h1 { font-size: 15pt; }
a { color: #111; text-decoration: none; word-break: break-all; }
"""


def to_html(md_text: str) -> str:
    html = markdown.markdown(md_text, extensions=["tables"])
    # Keep each table title with its table, and each figure with its caption, on the same page
    # Short tables stay in one block with their title; long ones may continue on the next page (header repeated)
    def keep_short(m):
        block = m.group(1)
        if block.count("<tr>") <= 8:
            return f'<div class="keep">{block}</div>'
        title, table = re.match(r"(<p><strong>Table [^<]*</strong></p>)\s*(<table>.*)", block, flags=re.S).groups()
        return f'<div class="keep-title">{title}</div><table class="long">{table[len("<table>"):]}'
    html = re.sub(r"(<p><strong>Table [^<]*</strong></p>\s*<table>.*?</table>)", keep_short, html, flags=re.S)
    html = re.sub(r"(<p><img[^>]*></p>\s*<p><em>Figure [^<]*</em></p>)", r'<div class="keep">\1</div>',
                  html, flags=re.S)
    # References: left-aligned, smaller (long URLs make justified text gappy)
    html = re.sub(r"(<h2>References</h2>)(.*?)(?=<p><em>Analysis in Python|$)", r'<div class="references">\1\2</div>',
                  html, flags=re.S)
    return html


def main() -> None:
    note = (PAPER / "draft_full.md").read_text()
    note = note.replace("*Appendix: `appendix.md` and `appendix_tables.md`.*", "")
    # Appendix: text sections, then the generated tables (without their "do not edit" line)
    app = (PAPER / "appendix.md").read_text()
    app = re.sub(r"^\*Draft.*?\*\n", "", app, flags=re.S | re.M)
    tables = (PAPER / "appendix_tables.md").read_text().split("\n", 1)[1]
    tables = re.sub(r"^\*Generated by.*?\*\n", "", tables, flags=re.M)
    # Figure A1 embedded in the appendix
    app = app.replace("Figure A1: `figures/figA1_correlations.png`",
                      "![Figure A1](figures/figA1_correlations.png)\n\n*Figure A1. Exports known at t and first-release "
                      "earnings, four panels; marker shape distinguishes quarters before 2023 and from 2023.*\n\n")
    body = (to_html(note) + f'<div class="appendix">{to_html(app)}{to_html(tables)}</div>')
    HTML.write_text(f'<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Chip Canary</title>'
                    f"<style>{CSS}</style></head><body>{body}</body></html>")
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={PDF}", HTML.resolve().as_uri()],
                   check=True, capture_output=True, timeout=120)
    reader = PdfReader(str(PDF))
    first_app = next((i for i, p in enumerate(reader.pages) if "A0. Data sources" in (p.extract_text() or "")), None)
    total = len(reader.pages)
    print(f"Saved: {PDF.relative_to(ROOT)} ({total} pages: note {first_app if first_app is not None else '?'}, "
          f"appendix {total - first_app if first_app is not None else '?'})")


if __name__ == "__main__":
    main()
